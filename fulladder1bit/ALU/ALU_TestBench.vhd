library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

entity ALU_8bit_TB is
end ALU_8bit_TB;


architecture Behavioral of ALU_8bit_TB is

    signal A     : STD_LOGIC_VECTOR(7 downto 0);
    signal B     : STD_LOGIC_VECTOR(7 downto 0);

    signal Cin   : STD_LOGIC;

    signal SEL   : STD_LOGIC_VECTOR(2 downto 0);

    signal Y     : STD_LOGIC_VECTOR(7 downto 0);

    signal Cout  : STD_LOGIC;


begin

    DUT : entity work.ALU_8bit
        port map (
            A    => A,
            B    => B,
            Cin  => Cin,
            SEL  => SEL,
            Y    => Y,
            Cout => Cout
        );


    process
    begin

        ------------------------------------------------
        -- AND
        ------------------------------------------------

        A <= "10101010";
        B <= "11001100";
        Cin <= '0';
        SEL <= "000";

        wait for 10 ns;


        ------------------------------------------------
        -- OR
        ------------------------------------------------

        SEL <= "001";

        wait for 10 ns;


        ------------------------------------------------
        -- XOR
        ------------------------------------------------

        SEL <= "010";

        wait for 10 ns;


        ------------------------------------------------
        -- NOR
        ------------------------------------------------

        SEL <= "011";

        wait for 10 ns;


        ------------------------------------------------
        -- NOT
        ------------------------------------------------

        SEL <= "100";

        wait for 10 ns;


        ------------------------------------------------
        -- ADD
        ------------------------------------------------

        A <= "00001111";
        B <= "00000001";
        Cin <= '0';
        SEL <= "101";

        wait for 10 ns;


        ------------------------------------------------
        -- ADD WITH CARRY
        ------------------------------------------------

        A <= "11111111";
        B <= "00000001";
        Cin <= '0';
        SEL <= "101";

        wait for 10 ns;


        ------------------------------------------------
        -- SUBTRACT
        ------------------------------------------------

        A <= "00001111";
        B <= "00000001";
        Cin <= '1';
        SEL <= "110";

        wait for 10 ns;


        ------------------------------------------------
        -- ZERO
        ------------------------------------------------

        SEL <= "111";

        wait for 10 ns;


        wait;

    end process;

end Behavioral;